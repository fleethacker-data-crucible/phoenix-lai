// Chat engine: model loading (GPU with CPU fallback), Gemma 4 chat template, KV-cache reuse across turns,
// sampling and streaming. C# 5 only.
using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Text;

namespace Phoenix
{
    public interface ILanguageModel : IDisposable
    {
        // Runs one token at position pos (positions must be fed in order); returns logits.
        float[] Forward(int token, int pos);
        // Feeds tokens[start .. start+count) at positions start..start+count-1; returns the last logits.
        float[] Prefill(IList<int> tokens, int start, int count);
        void Reset();
        int ContextLength { get; }
        int VocabSize { get; }
        // Earliest cached position that can be kept after `fed` tokens (0 = any; ring caches return more).
        int MinReuse(int fed);
        // Instant Recall: save the KV cache of positions pos0.. and put it back at another position (re-rotated).
        bool CanRecall { get; }
        // Speculative verification: feeds tokens[start .. start+count) (count <= 16) through the layers in one batched pass
        // (false when the model has no batched path); RowLogits(i) then computes the logits after token i on demand, so
        // the output layer (566 MB per row on Gemma's 262K vocabulary) is only paid for rows that are actually checked.
        bool PrefillRows(IList<int> tokens, int start, int count);
        float[] RowLogits(int row);
        KvSnapshot CaptureKv(int pos0, int count);
        void SpliceKv(KvSnapshot s, int dst0);
    }

    public sealed class ChatMessage
    {
        public string Role;   // "system", "user", "assistant"
        public string Text;
        public List<byte[]> Images;   // image files (PNG / JPEG ...) shown before the text of a user message; null: none
        public ChatMessage(string role, string text) { Role = role; Text = text; }
    }

    public sealed class GenerationStats
    {
        public int PromptTokens, ReusedTokens, GeneratedTokens, RecalledTokens;
        public int DraftedTokens, AcceptedTokens;   // speculation: guessed tokens checked / kept   // RecalledTokens: part of PromptTokens spliced, not read
        public double PromptSeconds, GenerateSeconds;
        public string StopReason = "";
        public double PromptTokensPerSecond { get { return PromptSeconds > 0 ? PromptTokens / PromptSeconds : 0; } }
        public double TokensPerSecond { get { return GenerateSeconds > 0 ? GeneratedTokens / GenerateSeconds : 0; } }
    }

    // One generated token's log-probability (natural log, over the model's raw distribution) and its most likely rivals.
